"""Generate a C++ header containing the Git state used to build an executable."""

import argparse
import json
import os
from pathlib import Path
import subprocess
import tempfile


def git(repo, *args):
    return subprocess.check_output(
        ["git", "-C", str(repo), *args], encoding="utf-8"
    ).strip()


def repository_state(repo):
    # Git otherwise walks up to the parent repository for an empty submodule.
    if Path(git(repo, "rev-parse", "--show-toplevel")).resolve() != repo.resolve():
        raise ValueError(f"Not an initialized Git repository: {repo}")
    return {
        "commit": git(repo, "rev-parse", "HEAD"),
        "dirty": bool(git(repo, "status", "--porcelain", "--untracked-files=normal",
                          "--ignore-submodules=none")),
    }


def submodule_paths(repo):
    modules_file = repo / ".gitmodules"
    if not modules_file.exists():
        return {}
    result = subprocess.run(
        ["git", "config", "--file", str(modules_file), "--null",
         "--get-regexp", r"^submodule\..*\.path$"],
        capture_output=True, encoding="utf-8", check=False,
    )
    if result.returncode not in (0, 1):
        raise RuntimeError(result.stderr.strip())
    paths = {}
    for entry in result.stdout.split("\0"):
        if entry:
            key, path = entry.split("\n", 1)
            paths[key[len("submodule."):-len(".path")]] = path
    return paths


def collect_version(repo, target, configuration, submodules):
    metadata = {
        "target": target,
        "configuration": configuration,
        "repository": repository_state(repo),
        "submodules": {},
    }
    paths = submodule_paths(repo)
    for name in submodules:
        if name not in paths:
            raise ValueError(f"Unknown submodule {name!r}; available: {', '.join(paths)}")
        path = paths[name]
        module_repo = (repo / path).resolve()
        if not module_repo.is_relative_to(repo.resolve()):
            raise ValueError(f"Submodule path is outside the repository: {path}")
        metadata["submodules"][name] = {"path": path, **repository_state(module_repo)}
    return metadata


def write_header(output, metadata, *, placeholder=False):
    # ASCII JSON is also safe for the minidump's ANSI comment stream.
    payload = json.dumps(metadata, indent=2, sort_keys=True, ensure_ascii=True) + "\n"
    literals = "\n".join("    " + json.dumps(line) for line in payload.splitlines(keepends=True))
    note = (
        "// Placeholder: Git metadata was not copied to this build environment.\n"
        "// Commit and dirty state are unknown; submodule versions are unavailable.\n"
        if placeholder else ""
    )
    content = (
        "// Generated by generate_build_version.py. Do not edit.\n"
        + note +
        "#pragma once\n\n"
        "namespace BuildVersion {\n"
        "inline constexpr char Metadata[] =\n" + literals + ";\n"
        "}\n"
    ).encode("ascii")
    if output.exists() and output.read_bytes() == content:
        return
    output.parent.mkdir(parents=True, exist_ok=True)
    temporary = None
    try:
        with tempfile.NamedTemporaryFile(dir=output.parent, delete=False) as stream:
            temporary = Path(stream.name)
            stream.write(content)
        os.replace(temporary, output)
    finally:
        if temporary is not None and temporary.exists():
            temporary.unlink()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repo", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--target", required=True)
    parser.add_argument("--configuration", default="")
    parser.add_argument("--submodule", action="append", default=[],
                        help="Submodule name from .gitmodules; repeat for multiple modules")
    args = parser.parse_args()
    try:
        repo = args.repo.resolve()
        # Remote source copies may omit .git. A .git file also counts (worktrees
        # and submodules), and a parent repository must not supply this version.
        if not (repo / ".git").exists():
            if args.output.is_file():
                return
            write_header(args.output, {
                "target": args.target,
                "configuration": args.configuration,
                "repository": {"commit": "unknown", "dirty": None},
                "submodules": {},
            }, placeholder=True)
            return
        metadata = collect_version(repo, args.target,
                                   args.configuration, args.submodule)
        write_header(args.output, metadata)
    except (OSError, ValueError, RuntimeError, subprocess.CalledProcessError) as error:
        parser.exit(1, f"Build version generation failed: {error}\n")


if __name__ == "__main__":
    main()
