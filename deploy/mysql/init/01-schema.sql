CREATE DATABASE IF NOT EXISTS mydb CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE mydb;
CREATE TABLE IF NOT EXISTS account (
    AccountNo INT NOT NULL PRIMARY KEY,
    ID VARCHAR(64) NOT NULL UNIQUE,
    PASS VARCHAR(128) NOT NULL,
    LoginState TINYINT NOT NULL DEFAULT 0
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS player (
    AccountNo INT NOT NULL,
    PlayerId INT NOT NULL DEFAULT 0,
    Nick VARCHAR(64) NOT NULL,
    HP INT NOT NULL DEFAULT 100,
    Coins INT NOT NULL DEFAULT 0,
    CharType TINYINT NOT NULL DEFAULT 0,
    ServerType TINYINT NOT NULL DEFAULT 0,
    LocationX FLOAT NOT NULL DEFAULT 100,
    LocationY FLOAT NOT NULL DEFAULT 100,
    PRIMARY KEY (AccountNo, PlayerId),
    CONSTRAINT player_account FOREIGN KEY (AccountNo) REFERENCES account(AccountNo)
) ENGINE=InnoDB;
